import { test } from 'node:test';
import assert from 'node:assert/strict';
import { openStore } from '../lib/store.mjs';
import { createGoogleAuth } from '../lib/google.mjs';
import { hashPassword } from '../lib/auth.mjs';
const clientId='test.apps.googleusercontent.com';
test('Google requires nonce, verified audience and email; new accounts activate immediately and cannot elevate privileges',async t=>{
  const store=openStore(':memory:');t.after(()=>store.db.close());
  let payload;
  const auth=createGoogleAuth(store,{clientId,verifyToken:async()=>payload});
  const start=()=>{const state=auth.issue('signin');payload={sub:'subject-1',email:'google@example.com',name:'Google friend',email_verified:true,iss:'https://accounts.google.com',aud:clientId,exp:Date.now()/1000+600,nonce:state.nonce};return state.token;};
  let token=start();payload.aud='attacker';await assert.rejects(auth.signin({credential:'signed'},token,()=>true),{status:401});
  token=start();payload.email_verified=false;await assert.rejects(auth.signin({credential:'signed'},token,()=>true),{status:401});
  token=start();payload.nonce='wrong';await assert.rejects(auth.signin({credential:'signed'},token,()=>true),{status:401});
  token=start();assert.equal((await auth.signin({credential:'signed',role:'admin',requestedRole:'admin'},token,()=>true)).pending,false);
  const user=store.db.prepare('SELECT * FROM users WHERE email=?').get(payload.email);
  assert.equal(user.role,'customer');assert.equal(user.status,'active');assert.equal(user.passwordEnabled,0);
  await assert.rejects(auth.signin({credential:'signed'},token,()=>true),{status:403});
  token=start();assert.equal((await auth.signin({credential:'signed'},token,()=>false)).userId,user.id);
  store.db.prepare("UPDATE users SET status='suspended' WHERE id=?").run(user.id);
  token=start();await assert.rejects(auth.signin({credential:'signed'},token,()=>true),{status:403});
});
test('matching email never auto-links; linking requires correct password and a user-bound nonce',async t=>{
  const store=openStore(':memory:');t.after(()=>store.db.close());
  const password='a-long-password-for-linking';
  store.db.prepare('INSERT INTO users(id,email,name,password,role) VALUES(?,?,?,?,?)').run('owner','owner@example.com','Owner',await hashPassword(password),'admin');
  const user=store.db.prepare('SELECT * FROM users WHERE id=?').get('owner');
  let payload;
  const auth=createGoogleAuth(store,{clientId,verifyToken:async()=>payload});
  const start=(intent='signin')=>{const state=auth.issue(intent,user);payload={sub:'owner-google',email:user.email,email_verified:true,iss:'accounts.google.com',aud:clientId,exp:Date.now()/1000+600,nonce:state.nonce};return state.token;};
  await assert.rejects(auth.signin({credential:'signed'},start(),()=>true),{status:409});
  await assert.rejects(auth.link(user,{credential:'signed',currentPassword:'bad'},start('link')),{status:403});
  assert.equal(auth.providers(user).linked,false);
  await assert.rejects(auth.link({...user,id:'other'},{credential:'signed',currentPassword:password},start('link')),{status:403});
  await auth.link(user,{credential:'signed',currentPassword:password},start('link'));
  assert.equal(auth.providers(user).linked,true);
  assert.equal((await auth.signin({credential:'signed'},start(),()=>false)).userId,user.id);
});
